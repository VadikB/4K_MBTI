def _connect(test_database_url, schema):
    connection = psycopg.connect(test_database_url, row_factory=dict_row)
    connection.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
    connection.commit()
    return connection


@pytest.mark.parametrize("email", ["existing@example.test", "new@example.test"])
def test_configured_superadmin_addition_has_no_account_or_membership_effect(
    test_database_url, isolation_schema, email
):
    with _connect(test_database_url, isolation_schema) as connection:
        with pytest.raises(HTTPException) as raised:
            routes._attach_user_to_organization(
                connection, organization_id=4, email=email, full_name="Изменённое имя",
                admission_source="admin_add", admitted_by_user_id=18,
            )
        assert raised.value.status_code == 409
        assert "супер" not in raised.value.detail.lower()
        assert connection.execute("SELECT COUNT(*) AS n FROM users").fetchone()["n"] == 1
        assert connection.execute("SELECT full_name FROM users WHERE id=72").fetchone()["full_name"] == "Служебное имя"
        assert connection.execute("SELECT COUNT(*) AS n FROM organization_memberships").fetchone()["n"] == 0
        assert connection.execute("SELECT COUNT(*) AS n FROM user_identities").fetchone()["n"] == 0


def test_platform_permission_and_normal_admin_participation(
    test_database_url, isolation_schema, monkeypatch
):
    monkeypatch.setattr(org_access.settings, "superadmin_emails_raw", "")
    with _connect(test_database_url, isolation_schema) as connection:
        connection.execute("INSERT INTO user_platform_roles VALUES (72,1,NULL)")
        connection.execute("INSERT INTO platform_role_permissions VALUES (1,1)")
        with pytest.raises(HTTPException):
            routes._attach_user_to_organization(
                connection, organization_id=4, email="existing@example.test",
                admission_source="csv_import", admitted_by_user_id=18,
            )
        assert connection.execute("SELECT COUNT(*) AS n FROM organization_memberships").fetchone()["n"] == 0
        assert not org_access.get_admin_scope(
            connection, SimpleNamespace(id=72, email="existing@example.test")
        ).can_admin
        connection.execute("UPDATE user_platform_roles SET revoked_at=NOW() WHERE user_id=72")
        connection.execute(
            """INSERT INTO organization_memberships
               (organization_id,user_id,role,is_participant) VALUES (4,72,'admin',FALSE)"""
        )
        routes._attach_user_to_organization(
            connection, organization_id=4, email="existing@example.test",
            admission_source="admin_add", admitted_by_user_id=18,
        )
        membership = connection.execute(
            "SELECT role,is_participant FROM organization_memberships WHERE user_id=72"
        ).fetchone()
        assert membership == {"role": "admin", "is_participant": True}
        monkeypatch.setattr(org_access, "ensure_configured_organizations", lambda _connection: None)
        assert org_access.get_admin_scope(
            connection, SimpleNamespace(id=72, email="existing@example.test")
        ).organization_ids == (4,)


def test_assessment_role_alone_does_not_grant_admin_scope(
    test_database_url, isolation_schema, monkeypatch
):
    monkeypatch.setattr(org_access.settings, "superadmin_emails_raw", "")
    monkeypatch.setattr(org_access, "ensure_configured_organizations", lambda _connection: None)
    with _connect(test_database_url, isolation_schema) as connection:
        user = SimpleNamespace(id=72, email="existing@example.test", role_id=99)
        assert not org_access.get_admin_scope(connection, user).can_admin
